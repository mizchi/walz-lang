import {readFile, writeFile, rm, lstat} from 'node:fs/promises';

const header = '// Generated by vite-plugin-walz (walz-esm-v1). Do not edit.\n';
const camel = name => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const quote = JSON.stringify;
const arrays = {i32:'Int32Array', i64:'BigInt64Array', f32:'Float32Array', f64:'Float64Array',
  s8:'Int8Array', u8:'Uint8Array', s16:'Int16Array', u16:'Uint16Array', u32:'Uint32Array', u64:'BigUint64Array'};

function parse(shape) {
  const tokens = shape.match(/[()]|[^\s()]+/g) ?? [];
  let index = 0;
  function next() {
    const token = tokens[index++];
    if (!token || token === ')') throw new Error(`Unsupported ABI shape: ${shape}`);
    if (token !== '(') return token;
    const list = [];
    while (tokens[index] !== ')') {
      if (index >= tokens.length) throw new Error(`Unsupported ABI shape: ${shape}`);
      list.push(next());
    }
    index++;
    return list;
  }
  const value = next();
  if (index !== tokens.length) throw new Error(`Unsupported ABI shape: ${shape}`);
  return value;
}

function type(shape, input, unit='"value"') {
  if (typeof shape === 'string') {
    if (['i32','f32','f64','s8','u8','s16','u16','u32'].includes(shape)) return 'number';
    if (['i64','u64'].includes(shape)) return 'bigint';
    if (shape === 'text' || shape === 'char') return 'string';
    if (shape === 'bool') return 'boolean';
    if (shape === 'bytes') return 'Uint8Array';
    if (shape === 'unit') return unit;
  } else {
    const [kind, ...args] = shape;
    const child = (value, context) => type(value, input, context);
    switch (kind) {
      case 'list': {
        const array = typeof args[0] === 'string' && arrays[args[0]];
        return array ? (input ? `(ReadonlyArray<${child(args[0])}> | ${array})` : array)
          : `${input ? 'ReadonlyArray' : 'Array'}<${child(args[0])}>`;
      }
      case 'pair': case 'tuple': return `[${args.map(value=>child(value)).join(', ')}]`;
      case 'future': return `${input ? 'PromiseLike' : 'WalzFuture'}<${child(args[0], 'void')}>`;
      case 'stream': return input ? `(Iterable<${child(args[0], 'void')}> | AsyncIterable<${child(args[0], 'void')}>)`
        : `WalzStream<${child(args[0], 'void')}>`;
      case 'option': return Array.isArray(args[0]) && args[0][0] === 'option'
        ? `({tag:"none"} | {tag:"some"; val:${child(args[0])}})`
        : `(${child(args[0])} | undefined)`;
      case 'result': return `(${args.map((value,i)=>`{tag:${quote(i?'err':'ok')}; val${input && value==='unit'?'?':''}:${child(value,'undefined')}}`).join(' | ')})`;
      case 'record': return `{${args.map(([name,value])=>`${quote(camel(name))}:${child(value)}`).join('; ')}}`;
      case 'flags': return `{${args.map(name=>`${quote(camel(name))}${input?'?':''}:boolean`).join('; ')}}`;
      case 'enum': return `(${args.map(quote).join(' | ')})`;
      case 'variant': return `(${args.map(([name,value])=>`{tag:${quote(name)}${value===undefined?'':`; val:${child(value)}`}}`).join(' | ')})`;
    }
  }
  throw new Error(`Unsupported ABI shape for TypeScript: ${JSON.stringify(shape)}`);
}

export function declarations(exports) {
  const fields = Object.values(exports).map(binding => {
    const params = binding.params.map((shape,i)=>`arg${i}:${type(parse(shape), true)}`).join(', ');
    let result = type(parse(binding.result), false, 'void');
    if (binding.suspends) result = `Promise<Awaited<${result}>>`;
    return `  ${quote(binding.jsName)}: (${params}) => ${result};`;
  });
  const names = Object.values(exports).map((binding,i)=>`declare const e${i}: WalzExports[${quote(binding.jsName)}];\nexport {e${i} as ${quote(binding.jsName)}};`);
  const shared = `export interface WalzFuture<T> extends PromiseLike<T> {
  [Symbol.asyncDispose](): void | PromiseLike<unknown>;
}

export interface WalzStream<T> extends AsyncIterableIterator<T> {
  readMany(max: number): Promise<{items: T[]; done: boolean}>;
  return(): Promise<IteratorResult<T>>;
}
`;
  return `${header}${shared}export interface WalzExports {\n${fields.join('\n')}\n}\n${names.join('\n')}\n`;
}

/** TypeScript Content Mapper coordinates are UTF-8, matching checker spans.
 * Generated aliases are navigation targets, never edits of Walz identifiers.
 */
export function projection(exports, fileName) {
  const text = declarations(exports), mappings = [];
  for (const [i, binding] of Object.values(exports).entries()) {
    const label = binding.declaration;
    if (!label || label.location.path !== fileName) continue;
    const original = label.span.start, size = label.span.end-original;
    const spans = [
      [text.indexOf(`  ${quote(binding.jsName)}: `)+3, binding.jsName.length],
      [text.indexOf(`declare const e${i}:`)+14, `e${i}`.length],
      [text.indexOf(`export {e${i} as ${quote(binding.jsName)}};`)+`export {e${i} as "`.length, binding.jsName.length],
    ];
    for (const [start,length] of spans) {
      mappings.push([Buffer.byteLength(text.slice(0,start)),Buffer.byteLength(text.slice(start,start+length)),original,size,1,27]);
    }
  }
  return {text, extension:'.ts', mappings:mappings.sort((a,b)=>a[0]-b[0])};
}

const path = source => source.replace(/\.walz$/, '.d.walz.ts');
async function owned(source) {
  try {
    const info = await lstat(path(source));
    return info.isFile() && (await readFile(path(source), 'utf8')).startsWith(header);
  } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}
export async function writeDeclaration(source, text) {
  const existing = await owned(source);
  if (existing === false) throw new Error(`Refusing to overwrite a user declaration: ${path(source)}`);
  if (existing && await readFile(path(source), 'utf8') === text) return;
  await writeFile(path(source), text, {flag:existing ? 'w' : 'wx'});
}
export async function removeDeclaration(source) {
  if (await owned(source)) await rm(path(source));
}
